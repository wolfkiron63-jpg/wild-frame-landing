let lightboxEl=null;
function ensureLightbox(){
  if(lightboxEl) return lightboxEl;
  lightboxEl=document.createElement('div');
  lightboxEl.className='image-lightbox';
  lightboxEl.setAttribute('aria-hidden','true');
  lightboxEl.innerHTML=`<button class="lightbox-close" type="button" aria-label="Close image">×</button><div class="lightbox-stage"><img alt="Project still enlarged"></div>`;
  document.body.appendChild(lightboxEl);
  lightboxEl.addEventListener('click',e=>{if(e.target===lightboxEl) closeLightbox();});
  lightboxEl.querySelector('.lightbox-close').addEventListener('click',closeLightbox);
  document.addEventListener('keydown',e=>{if(e.key==='Escape' && lightboxEl?.classList.contains('open')) closeLightbox();});
  return lightboxEl;
}
function openLightbox(src){
  const box=ensureLightbox();
  const img=box.querySelector('img');
  img.src=src;
  box.classList.add('open');
  box.setAttribute('aria-hidden','false');
  document.body.classList.add('lightbox-open');
}
function closeLightbox(){
  if(!lightboxEl) return;
  lightboxEl.classList.remove('open');
  lightboxEl.setAttribute('aria-hidden','true');
  document.body.classList.remove('lightbox-open');
}

