let wheelTarget=0;
let wheelRaf=null;
function animateHorizontalScroll(){
  const diff=wheelTarget-shell.scrollLeft;
  if(Math.abs(diff)<0.5){
    shell.scrollLeft=wheelTarget;
    wheelRaf=null;
    return;
  }
  shell.scrollLeft+=diff*0.22;
  wheelRaf=requestAnimationFrame(animateHorizontalScroll);
}
shell.addEventListener('wheel',e=>{
  if(Math.abs(e.deltaY)<=Math.abs(e.deltaX)) return;
  const max=shell.scrollWidth-shell.clientWidth;
  if(max<=0) return;
  const direction=Math.sign(e.deltaY);
  const atStart=shell.scrollLeft<=1;
  const atEnd=shell.scrollLeft>=max-1;
  if((direction<0&&atStart)||(direction>0&&atEnd)) return;
  e.preventDefault();
  wheelTarget=Math.max(0,Math.min(max,(wheelRaf?wheelTarget:shell.scrollLeft)+e.deltaY*0.9));
  if(!wheelRaf) wheelRaf=requestAnimationFrame(animateHorizontalScroll);
},{passive:false});
let dragging=false,startX=0,startScroll=0;
shell.addEventListener('pointerdown',e=>{
  dragging=true;
  if(wheelRaf){cancelAnimationFrame(wheelRaf);wheelRaf=null;}
  startX=e.clientX;startScroll=shell.scrollLeft;
  shell.setPointerCapture(e.pointerId);
});
shell.addEventListener('pointermove',e=>{if(dragging)shell.scrollLeft=startScroll-(e.clientX-startX)});
['pointerup','pointercancel','pointerleave'].forEach(type=>shell.addEventListener(type,()=>{dragging=false;wheelTarget=shell.scrollLeft;}));

