function setActiveWorkCategory(category,{scrollToEnd=false}={}){
  activeWorkCategory=category;
  document.querySelectorAll('.work-category-tab').forEach(tab=>{
    tab.classList.toggle('active',tab.dataset.category===category);
  });
  renderProjects();
  requestAnimationFrame(()=>{
    requestAnimationFrame(()=>{
      const max=Math.max(0,shell.scrollWidth-shell.clientWidth);
      shell.scrollLeft=scrollToEnd?max:0;
      wheelTarget=shell.scrollLeft;
      updateProgress();
    });
  });
}

function moveToAdjacentCategory(direction){
  const currentIndex=workCategoryOrder.indexOf(activeWorkCategory);
  const nextIndex=(currentIndex+direction+workCategoryOrder.length)%workCategoryOrder.length;
  const nextCategory=workCategoryOrder[nextIndex];
  setActiveWorkCategory(nextCategory,{scrollToEnd:direction<0});
}

function slideWork(direction){
  const max=Math.max(0,shell.scrollWidth-shell.clientWidth);
  const atStart=shell.scrollLeft<=4;
  const atEnd=shell.scrollLeft>=max-4;

  if(direction<0 && atStart){
    moveToAdjacentCategory(-1);
    return;
  }
  if(direction>0 && atEnd){
    moveToAdjacentCategory(1);
    return;
  }

  const card=shell.querySelector('.project-card');
  const gap=24;
  const step=card ? card.getBoundingClientRect().width+gap : shell.clientWidth*.75;
  shell.scrollBy({left:direction*step,behavior:'smooth'});
  setTimeout(()=>{wheelTarget=shell.scrollLeft;updateProgress();},420);
}
if(workPrev) workPrev.addEventListener('click',()=>slideWork(-1));
if(workNext) workNext.addEventListener('click',()=>slideWork(1));

